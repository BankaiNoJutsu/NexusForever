#!/usr/bin/env python3
"""Generate Tools/DataMapping/sql/jabbithole_instance_boss_wip_seed.sql.

Spawn rows for the ten scripted instance bosses that have no `entity` row in the runtime world data.
Inputs (read-only):
  * Decomp/Analysis/coverage/jabbithole_boss_coordinates_20261109.csv (Jabbithole sighting medians, built by
    Decomp/Analysis/scripts/instance_jabbithole_coordinates.py),
  * the client Creature2 and Creature2DisplayGroupEntry tables (faction = Creature2 word 100, display info = the entry of the
    display group in word 11; both verified against the ten existing boss rows),
  * world ids from the repo's own map scripts.
Evidence: position Correlated (Jabbithole sightings, same coordinate space as `entity`), faction and display info Mapped from the
client tables. Area, facing and event phase are NOT known: area 0, rotation 0 and no entity_event row are used. WIP/GUESSED.
"""
import csv, os, struct, sys
sys.stdout.reconfigure(encoding='utf-8')
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CSV = os.path.join(ROOT, 'Decomp', 'Analysis', 'coverage', 'jabbithole_boss_coordinates_20261109.csv')
OUT = os.path.join(ROOT, 'Tools', 'DataMapping', 'sql', 'jabbithole_instance_boss_wip_seed.sql')
DB = r'I:\tools\extract\DB'

# class -> (label, creature2 id, world, why this id)
BOSSES = [
    ('Stormtalon', "Stormtalon's Lair Stormtalon", 33406, 382, 'veteran id, matching the seeded Blade-Wind and Aethros rows'),
    ('Octog', 'Skullcano Bosun Octog', 24486, 1263, 'normal id, matching the seeded Thunderfoot and Tugga rows'),
    ('Mordechai', 'Skullcano Mordechai Redmoon', 24489, 1263, 'normal id, matching the seeded Thunderfoot and Tugga rows'),
    ('Ondu', 'Sanctuary of the Swordmaiden Ondu Lifeweaver', 28721, 1271, 'normal id (Creature2 word 9 = 1)'),
    ('Skash', 'Sanctuary of the Swordmaiden Moldwood Overlord Skash', 28727, 1271, 'normal id (Creature2 word 9 = 1)'),
    ('Rayna', 'Sanctuary of the Swordmaiden Rayna Darkspeaker', 28733, 1271, 'normal id (Creature2 word 9 = 1)'),
    ('Selene', 'Sanctuary of the Swordmaiden Spiritmother Selene the Corrupted', 28735, 1271, 'normal id (Creature2 word 9 = 1)'),
    ('PhageMaw', 'Genetic Archives Phage Maw', 52974, 1462, 'only id'),
    ('MaelstromAuthority', 'Datascape Maelstrom Authority', 30497, 1333, 'only id'),
    ('Wrathbone', 'Protogames Academy Wrathbone', 67944, 3173, 'only id'),
]


def load(name):
    d = open(os.path.join(DB, name + '.tbl'), 'rb').read()
    rs = struct.unpack_from('<Q', d, 24)[0]; n = struct.unpack_from('<Q', d, 48)[0]; b = 0x60 + struct.unpack_from('<Q', d, 64)[0]
    return [struct.unpack_from('<%dI' % (rs // 4), d, b + i * rs) for i in range(n)]


c2 = {r[0]: r for r in load('Creature2')}
groups = {}
for e in load('Creature2DisplayGroupEntry'):
    groups.setdefault(e[1], []).append(e[2])
csvrows = list(csv.DictReader(open(CSV, encoding='utf-8')))

rows, notes = [], []
for i, (cls, label, cid, world, why) in enumerate(BOSSES, 1):
    cand = [r for r in csvrows if r['script_class'] == cls and int(r['creature2_id']) == cid and r['status'] == 'NO_entity_row']
    best = max(cand, key=lambda r: int(r['jabbithole_points']))
    x, y, z = best['x_or_jabbithole_median_x'], best['y'], best['z']
    disp = groups[c2[cid][11]]
    assert len(disp) == 1, (cid, disp)
    faction = c2[cid][100]
    eid = 1100310000 + i
    rows.append(f'  ({eid}, 0, {cid}, {world}, 0, {x}, {y}, {z}, 0, 0, 0, {disp[0]}, 0, {faction}, {faction}, 0, 0, 0, 0)')
    notes.append(f'--   {eid}: {label}; Creature2 {cid} ({why}); world {world}; position = median of {best["jabbithole_points"]} Jabbithole sightings '
                 f'(creature {best["jabbithole_creature_id"]}, zone {best["jabbithole_zone"]}); displayInfo {disp[0]} and faction {faction} from the client tables.')

sql = f"""-- Generated by Tools/DataMapping/build_jabbithole_instance_boss_seed.py.
-- Source: Jabbithole coordinates.sql sightings (Correlated) plus the client Creature2 tables (Mapped for faction and display info).
-- Purpose: give the ten provisional boss scripts that have no spawn row in the runtime world data something to attach to.
-- WIP/GUESSED: area is 0, facing is 0 and there is no entity_event row (so each boss exists for the whole instance, not at its phase);
-- positions are medians of sightings, which can drift for creatures that move. Manual client smoke is required before any parity claim.
-- Not wired into any setup script: apply by hand after the runtime world seed. Ids 1100310001 to 1100310010 sit inside the
-- 1100300000 to 1100399999 range that runtime_world_seed.sql leaves alone.

USE `nexus_forever_world`;

START TRANSACTION;

-- Entity evidence and WIP scope:
{chr(10).join(notes)}

-- entity: {len(rows)} row(s)
INSERT INTO `entity` (`id`, `type`, `creature`, `world`, `area`, `x`, `y`, `z`, `rx`, `ry`, `rz`, `displayInfo`, `outfitInfo`, `faction1`, `faction2`, `questChecklistIdx`, `activePropId`, `worldSocketId`, `mode`) VALUES
{(',' + chr(10)).join(rows)}
ON DUPLICATE KEY UPDATE `type` = VALUES(`type`), `creature` = VALUES(`creature`), `world` = VALUES(`world`), `area` = VALUES(`area`), `x` = VALUES(`x`), `y` = VALUES(`y`), `z` = VALUES(`z`), `rx` = VALUES(`rx`), `ry` = VALUES(`ry`), `rz` = VALUES(`rz`), `displayInfo` = VALUES(`displayInfo`), `outfitInfo` = VALUES(`outfitInfo`), `faction1` = VALUES(`faction1`), `faction2` = VALUES(`faction2`), `questChecklistIdx` = VALUES(`questChecklistIdx`), `activePropId` = VALUES(`activePropId`), `worldSocketId` = VALUES(`worldSocketId`), `mode` = VALUES(`mode`);

COMMIT;
"""
open(OUT, 'w', encoding='utf-8', newline='\n').write(sql)
print(sql)
